"""Reproduce the synthetic churn benchmark; run from the repository root."""
import json
import platform
from pathlib import Path
from tempfile import TemporaryDirectory
from importlib.metadata import version
from fastapi.testclient import TestClient
from ml_pipeline.train import train_pipeline
from app.main import app


def main():
    with TemporaryDirectory() as directory:
        result = train_pipeline(tracking_uri=Path(directory).as_uri())
    for key in ["model_path", "metrics_path", "model_card_path"]:
        result.pop(key)
    result.update({
        "dataset": "600 synthetic churn records generated by ml_pipeline.data_loader; seed 42",
        "method": "Stratified 60/20/20 train/validation/test; select by validation F1, report held-out test once; no refit",
        "baseline": "DummyClassifier most_frequent, fitted only on training rows",
        "limitations": "Single synthetic seed, small holdout, no real-world or production accuracy claim",
        "python": platform.python_version(),
        "versions": {name: version(name) for name in ["scikit-learn", "numpy", "pandas", "mlflow"]},
    })
    request = {"tenure_months":6,"monthly_charges":95.5,"total_charges":573.0,
               "contract_type":"month-to-month","internet_service":"fiber",
               "payment_method":"electronic_check","support_calls":3,
               "has_online_security":False,"is_senior_citizen":True}
    with TestClient(app) as client:
        response = client.post("/predict", json=request)
        response.raise_for_status()
    result["api_example"] = {"request": request, "response": response.json()}
    Path("evaluation/results.json").write_text(json.dumps(result, indent=2)+"\n")
    print(json.dumps(result, indent=2))

if __name__ == "__main__":
    main()
